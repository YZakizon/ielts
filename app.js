async function searchVocabulary() {
  const rawQuery = searchInput.value.trim();
  const query = rawQuery.toLowerCase();
  if (!query) {
    setStatus("Type a vocabulary word to search.", true);
    return;
  }

  let match =
    currentWords.find((item) => item.word.toLowerCase() === query) ||
    currentWords.find((item) => item.word.toLowerCase().includes(query)) ||
    allSavedGeneratedWords().find((item) => item.word.toLowerCase() === query) ||
    allSavedGeneratedWords().find((item) => item.word.toLowerCase().includes(query)) ||
    allLocalWords().find((item) => item.word.toLowerCase() === query) ||
    allLocalWords().find((item) => item.word.toLowerCase().includes(query));

  if (!match) {
    searchBtn.disabled = true;
    setStatus(`Searching "${rawQuery}" with generation...`);

    try {
      match = await searchWithAi(
        rawQuery,
        englishVariantSelect.value,
        vocabTargetLanguageSelect.value,
      );
    } catch (error) {
      const message =
        error.name === "AbortError"
          ? `Search took too long for "${rawQuery}".`
          : `No vocabulary found for "${rawQuery}". ${error.message.slice(0, 120)}`;
      setStatus(message, true);
      return;
    } finally {
      searchBtn.disabled = false;
    }
  }

  if (!currentWords.some((item) => item.word === match.word)) {
    currentWords = [match, ...currentWords.slice(0, 19)];
  }

  currentWordIndex = currentWords.findIndex((item) => item.word === match.word);
  selectedWord = match;
  selectWord(match);
  setStatus(`Found "${match.word}".`);
  saveAppState();
}

