    translation: String(item?.translation || "").trim(),
    synonyms: Array.isArray(item?.synonyms)
      ? item.synonyms.slice(0, 6).map((synonym) => String(synonym).trim()).filter(Boolean)
      : [],
    usage: String(item?.usage || "").trim(),
