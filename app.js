function loadHistory() {
  try {
    const saved = JSON.parse(localStorage.getItem(historyStorageKey) || "[]");
    historyWords = Array.isArray(saved) ? saved.map(withLocalDetails).slice(0, 20) : [];
  } catch {
    historyWords = [];
  }

  try {
    const savedBatches = JSON.parse(localStorage.getItem(generatedStorageKey) || "[]");
    generatedBatches = Array.isArray(savedBatches)
      ? savedBatches
          .map((batch) => ({
            ...batch,
            words: Array.isArray(batch.words) ? batch.words.map(withLocalDetails) : [],
          }))
          .filter((batch) => batch.words.length)
          .slice(0, 20)
      : [];
  } catch {
    generatedBatches = [];
  }
}

function saveHistory() {
  try {
    localStorage.setItem(historyStorageKey, JSON.stringify(historyWords.slice(0, 20)));
    localStorage.setItem(generatedStorageKey, JSON.stringify(generatedBatches.slice(0, 20)));
  } catch {
    setStatus("History could not be saved in this browser.", true);
  }
}

