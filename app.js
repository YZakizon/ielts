function loadAppState() {
  try {
    const saved = JSON.parse(localStorage.getItem(appStateStorageKey) || "null");
    if (!saved || !Array.isArray(saved.currentWords) || !saved.currentWords.length) {
      return false;
    }

    if (labels[saved.level]) {
      levelSelect.value = saved.level;
    }
    if (englishVariantLabels[saved.variant]) {
      englishVariantSelect.value = saved.variant;
    }
    if (translationLanguageLabels[saved.targetLanguage]) {
      vocabTargetLanguageSelect.value = saved.targetLanguage;
    }

    oneByOneToggle.checked = Boolean(saved.oneByOne);
    currentWords = saved.currentWords.map(withLocalDetails);
    currentWordIndex = Number.isInteger(saved.currentWordIndex)
      ? Math.min(Math.max(saved.currentWordIndex, 0), currentWords.length - 1)
      : 0;
    selectedWord = currentWords.find((item) => item.word === saved.selectedWord) || null;

    renderList();
    if (selectedWord) {
      renderDetail(selectedWord);
    } else if (oneByOneToggle.checked && currentWords[currentWordIndex]) {
      selectWord(currentWords[currentWordIndex], false);
    } else {
      renderEmptyState();
    }
    showView(saved.view === "history" ? "history" : "vocab", false);
    return true;
  } catch {
    return false;
  }
}

